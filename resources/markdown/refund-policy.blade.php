## Refunds and cancellation

- Payments are generally non-refundable after publication or substantial delivery of paid benefits. Disappointing results or a change of mind after delivery do not qualify.
- Request cancellation before publication by email. We review eligibility individually; a cancellation request does not automatically stop a scheduled launch or guarantee a refund.
- Report duplicate or accidental payments within 14 days for a full-refund review.
- If our technical or operational failure prevents delivery, we will correct it or refund the undelivered service.
- If our team rejects your product before delivering paid benefits, you may request a refund.

## Listing conditions

Listings are permanent subject to suitability review and our Terms of Use. Removing a badge automatically removes a badge listing from public view. Paid listings do not require a badge. Withholding or removing a paid listing before benefits are delivered is covered by the rejection provision above.

Removal after delivery for deceptive information, unlawful products, fraudulent payments, or manipulated engagement does not normally qualify for a refund.

